import java.util.Scanner;

public class diadasemana {
    static void main() {

        Scanner sc = new Scanner(System.in);

        IO.println("Digite um número existente");

        int dias = sc.nextInt();

        switch (dias) {

            case 1:
                IO.println("Hoje é Domingo");
                break;

            case 2:
                IO.println("Hoke é Segunda");
                break;

            case 3:
                IO.println("Hoje é Terça");
                break;

            case 4:
                IO.println("Hoje é Quarta");
                break;

            case 5:
                IO.println("Hoje é Quinta");
                break;

            case 6:
                IO.println("Hoje é Sexta");
                break;

            case 7:
                IO.println("Hoje é Sábado");
                break;













        }
    }
}